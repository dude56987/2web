# enable debug log
#set -x
################################################################################
source /var/lib/2web/common
################################################################################
function update(){
	# this will launch a processing queue that downloads updates to ai
	INFO "Loading up prompt models..."
	# load up the configs
	aiPromptModels=$(loadConfigs "/etc/2web/ai/promptModels.cfg" "/etc/2web/ai/promptModels.d/" "/etc/2web/config_default/ai2web_promptModels.cfg" | tr -s '\n' | shuf)
	txt2imgModels=$(loadConfigs "/etc/2web/ai/txt2imgModels.cfg" "/etc/2web/ai/txt2imgModels.d/" "/etc/2web/config_default/ai2web_txt2imgModels.cfg" | tr -s '\n' | shuf)
	aiAudioModels=$(loadConfigs "/etc/2web/ai/audioModels.cfg" "/etc/2web/ai/audioModels.d/" "/etc/2web/config_default/ai2web_audioModels.cfg" | tr -s '\n' | shuf)
	################################################################################
	webDirectory=$(webRoot)
	kodiDirectory="$(kodiRoot)"
	################################################################################
}
################################################################################
function resetCache(){
	# reset all generated/downloaded content
	webDirectory=$(webRoot)
	kodiDirectory="$(kodiRoot)"
	downloadDirectory="/var/cache/2web/downloads/ai/"
	# remove all the index files generated by the website
	find "$webDirectory/ai/" -name "*.index" -delete
	# remove web cache
	rm -rv "$webDirectory/ai/" || INFO "No ai web directory at '$webDirectory/ai/'"
	#
	echo "You MUST remove downloaded ai manually they are stored at:"
	echo "$downloadDirectory"
}
################################################################################
function nuke(){
	webDirectory="$(webRoot)"
	kodiDirectory="$(kodiRoot)"
	# remove ai directory and indexes
	delete "$webDirectory/ai/"
	# remove the cached conversations
	delete "$webDirectory/ai/convos.db"
	rm -rv $webDirectory/sums/ai2web_*.cfg || echo "No file sums found..."
	# remove widgets cached
	delete $webDirectory/web_cache/widget_random_ai.index
	delete $webDirectory/web_cache/widget_new_ai.index
}
################################################################################
# set the theme of the lines in CLI output
LINE_THEME="flowersRand"
################################################################################
if [ "$1" == "-w" ] || [ "$1" == "--webgen" ] || [ "$1" == "webgen" ] ;then
	lockProc "ai2web"
	checkModStatus "ai2web"
	webUpdate "$@"
elif [ "$1" == "-u" ] || [ "$1" == "--update" ] || [ "$1" == "update" ] ;then
	lockProc "ai2web"
	checkModStatus "ai2web"
	update "$@"
elif [ "$1" == "-U" ] || [ "$1" == "--upgrade" ] || [ "$1" == "upgrade" ] ;then
	lockProc "ai2web"
	checkModStatus "ai2web"
	# - no tensor libraries
	# - no diffusion
	# - langMan will be used
elif [ "$1" == "-e" ] || [ "$1" == "--enable" ] || [ "$1" == "enable" ] ;then
	enableMod "ai2web"
elif [ "$1" == "-d" ] || [ "$1" == "--disable" ] || [ "$1" == "disable" ] ;then
	disableMod "ai2web"
elif [ "$1" == "-n" ] || [ "$1" == "--nuke" ] || [ "$1" == "nuke" ] ;then
	nuke
elif [ "$1" == "-r" ] || [ "$1" == "--reset" ] || [ "$1" == "reset" ] ;then
	resetCache
elif [ "$1" == "-h" ] || [ "$1" == "--help" ] || [ "$1" == "help" ] ;then
	cat "/usr/share/2web/help/ai2web.txt"
elif [ "$1" == "-v" ] || [ "$1" == "--version" ] || [ "$1" == "version" ];then
	echo -n "Build Date: "
	cat /usr/share/2web/buildDate.cfg
	echo -n "ai2web Version: "
	cat /usr/share/2web/version_ai2web.cfg
else
	lockProc "ai2web"
	checkModStatus "ai2web"
	#
	drawLine
	drawSmallHeader "Currently Broken"
	drawLine
	ALERT "ai2web is currently being reworked to use langMan CLI utility\nAll Tensor based LLMs have been removed.\nYou can add external AI tools on the server using php2web or by linking local services or external servers in portal2web."
	drawLine
	exit
	#
	update "$@"
	webUpdate "$@"
	# on default execution show the server links at the bottom of output
	showServerLinks
	echo "Module Links"
	drawLine
	echo "http://$(hostname).local:80/ai/"
	drawLine
	echo "http://$(hostname).local:80/settings/ai.php"
	drawLine
fi
